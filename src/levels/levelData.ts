/** 关卡来源：主线剧情关 / 运行时随机生成 / 玩家自定义 */
export type LevelSource = 'campaign' | 'random' | 'custom';

/** 关卡定义 */
export interface LevelDefinition {
  id: number;
  /** 来源，缺省视为主线关卡 */
  source?: LevelSource;
  /** 随机关卡的生成参数（source = random 时存在，可用于复现与分享） */
  random?: RandomLevelParams;
  /** 分享码：随机关卡为种子码，自定义关卡为地图码 */
  code?: string;
  /** 自定义关卡在本地存储中的 id */
  customId?: string;
  title: string;
  subtitle: string;
  /** 等宽字符串地图：# 墙 / . 地面 / S 出生点 / R 共振节点 / E 出口 / ^ 尖刺 / * 回声干扰器 */
  map: string[];
  /** 通关需要激活的节点数量（等于地图中 R 的数量） */
  requiredResonators: number;
  /** 覆盖默认声波参数 */
  sonar?: Partial<SonarConfig>;
  /** 覆盖默认陷阱参数（生命上限、伤害、干扰半径等） */
  hazard?: Partial<HazardConfig>;
  /** 关卡提示，显示在标题页或 HUD */
  hint: string[];
  /** 教学关的分步引导（只在教学关配置） */
  tutorial?: TutorialStep[];
}

